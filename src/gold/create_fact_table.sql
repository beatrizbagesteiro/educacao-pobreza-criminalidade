        STDDEV(c.in_lixo_descarta_outra_area) AS dp_lixo_descarta_outra_area,
        AVG(c.in_banheiro) AS m_banheiro,
        STDDEV(c.in_banheiro) AS dp_banheiro,
        AVG(c.in_banheiro_ei) AS m_banheiro_ei,
        STDDEV(c.in_banheiro_ei) AS dp_banheiro_ei,
        AVG(c.in_banheiro_pne) AS m_banheiro_pne,
        STDDEV(c.in_banheiro_pne) AS dp_banheiro_pne,
        AVG(c.in_banheiro_funcionarios) AS m_banheiro_funcionarios,
        STDDEV(c.in_banheiro_funcionarios) AS dp_banheiro_funcionarios,
