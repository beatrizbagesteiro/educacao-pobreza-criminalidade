    JOIN gold.d_municipio d ON d.co_municipio = c.co_municipio
    GROUP BY d.co_municipio
),
metricas_cad_unico AS (
    SELECT 
        d.co_municipio,
        AVG(cd_u.familias_pobreza) as m_familas_probreza,
        STDDEV(cd_u.familias_pobreza) as dp_familas_probreza,
        AVG(cd_u.familias_baixa_renda) as m_familias_baixa_renda,
        STDDEV(cd_u.familias_baixa_renda) as dp_familias_baixa_renda,
        AVG(cd_u.familias_acima_meio_sm) as m_familias_acima_meio_sm,
        STDDEV(cd_u.familias_acima_meio_sm) as dp_familias_acima_meio_sm
    FROM silver.cad_unico_2024 cd_u
    JOIN gold.d_municipio d ON d.co_municipio = cd_u.co_municipio
    WHERE EXTRACT(MONTH FROM cd_u.referencia) = 12
    GROUP BY d.co_municipio
)
